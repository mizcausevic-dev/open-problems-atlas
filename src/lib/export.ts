/**
 * Escape text for LaTeX. Note the deliberate exception: `$` is left alone,
 * because the note body is written in LaTeX-flavoured markdown where $...$ is
 * how the user writes maths. Escaping it would break every formula they typed.
 */
function tex(s: string): string {
  return s
    .replace(/\\/g, '\\textbackslash{}')
    .replace(/([&%#_{}])/g, '\\$1')
    .replace(/~/g, '\\textasciitilde{}')
    .replace(/\^/g, '\\textasciicircum{}');
}

/** Same, but leaves $...$ spans untouched so inline maths survives. */
function texKeepMath(s: string): string {
  return s
    .split(/(\$[^$]*\$)/g)
    .map((part) => (part.startsWith('$') && part.endsWith('$') && part.length > 1 ? part : tex(part)))
    .join('');
}

export function toLaTeX(data: UserData, problems: Problem[]): string {
  const byId = new Map(problems.map((p) => [p.id, p]));
  const tracked = Object.values(data.tracked).sort((a, b) => b.updatedAt.localeCompare(a.updatedAt));
  const date = new Date().toISOString().slice(0, 10);

  const lines: string[] = [
    '% Generated by Open Problems Atlas.',
    '% Problem titles and descriptions are from the English Wikipedia article',
    '% "List of unsolved problems in mathematics", CC BY-SA 4.0.',
    '% Notes and status are the author\'s own.',
    '\\documentclass[11pt,a4paper]{article}',
    '\\usepackage[utf8]{inputenc}',
    '\\usepackage[T1]{fontenc}',
    '\\usepackage{amsmath,amssymb,amsthm}',
    '\\usepackage[margin=2.5cm]{geometry}',
    '\\usepackage{hyperref}',
    '\\title{Research Journal}',
    `\\date{${date}}`,
    '\\begin{document}',
    '\\maketitle',
    '',
  ];

  if (tracked.length) {
    lines.push('\\section*{Problems being tracked}', '\\begin{itemize}');
    for (const t of tracked) {
      const p = byId.get(t.problemId);
      const title = tex(p?.title ?? t.problemId);
      const field = p ? ` \\textit{(${tex(p.field)})}` : '';
      const difficulty =
        t.perceivedDifficulty !== undefined ? `, self-rated ${t.perceivedDifficulty}/5` : '';
      lines.push(`  \\item \\textbf{${title}}${field} --- ${tex(t.state)}${difficulty}`);
    }
    lines.push('\\end{itemize}', '');
  }

  const journal = [...data.journal].sort((a, b) => a.problemId.localeCompare(b.problemId));
  if (journal.length) {
    lines.push('\\section*{Notes}', '');
    let currentProblem = '';
    for (const entry of journal) {
      if (entry.problemId !== currentProblem) {
        currentProblem = entry.problemId;
        const p = byId.get(currentProblem);
        lines.push(`\\subsection*{${tex(p?.title ?? currentProblem)}}`);
        if (p?.description) lines.push(`\\textit{${texKeepMath(p.description)}}`, '');
        if (p?.wikipediaTitle) {
          const url = `https://en.wikipedia.org/wiki/${encodeURIComponent(p.wikipediaTitle.replace(/ /g, '_'))}`;
          lines.push(`\\noindent\\small Source: \\url{${url}}\\normalsize`, '');
        }
      }
      lines.push(`\\paragraph{${tex(entry.title)}}`);
      lines.push(`\\small Last edited ${entry.updatedAt.slice(0, 10)}.\\normalsize`, '');
      lines.push(texKeepMath(entry.body), '');
    }
  }

  if (!tracked.length && !journal.length) {
    lines.push('\\noindent No problems tracked and no notes written yet.', '');
  }

  lines.push('\\end{document}', '');
  return lines.join('\n');
}

