// Markdown
// ---------------------------------------------------------------------------

export function toMarkdown(data: UserData, problems: Problem[]): string {
  const byId = new Map(problems.map((p) => [p.id, p]));
  const out: string[] = ['# Research journal', '', `Exported ${new Date().toISOString().slice(0, 10)}.`, ''];

  const tracked = Object.values(data.tracked).sort((a, b) => b.updatedAt.localeCompare(a.updatedAt));
  if (tracked.length) {
    out.push('## Tracking', '', '| Problem | Field | State | Self-rated |', '| --- | --- | --- | --- |');
    for (const t of tracked) {
      const p = byId.get(t.problemId);
      out.push(
        `| ${p?.title ?? t.problemId} | ${p?.field ?? '?'} | ${t.state} | ${
          t.perceivedDifficulty ? `${t.perceivedDifficulty}/5` : '—'
        } |`,
      );
    }
    out.push('');
  }

  for (const entry of [...data.journal].sort((a, b) => b.updatedAt.localeCompare(a.updatedAt))) {
    const p = byId.get(entry.problemId);
    out.push(`## ${entry.title}`, '', `**Problem:** ${p?.title ?? entry.problemId}  `);
    out.push(`**Last edited:** ${entry.updatedAt.slice(0, 10)}`, '', entry.body, '');
  }
  return out.join('\n');
}

