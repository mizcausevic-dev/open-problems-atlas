/**
 * Export and import.
 *
 * Data portability here means one thing: a file the user can open without this
 * app. The JSON backup is the complete user record and can be re-imported. The
 * LaTeX export compiles in any TeX distribution with no custom package. PDF is
 * produced through the browser's own print pipeline rather than by bundling a
 * PDF library, which keeps a ~300 KB dependency out of the build for a job the
 * platform already does well.
 */

import type { Problem, UserData } from '../types';

export interface BackupFile {
  format: 'open-problems-atlas-backup';
  version: 1;
  exportedAt: string;
  data: UserData;
}

export function toBackup(data: UserData): BackupFile {
  return {
    format: 'open-problems-atlas-backup',
    version: 1,
    exportedAt: new Date().toISOString(),
    data,
  };
}

export class ImportError extends Error {}

export function parseBackup(text: string): UserData {
  let parsed: unknown;
  try {
    parsed = JSON.parse(text);
  } catch {
    throw new ImportError('That file is not valid JSON.');
  }
  const file = parsed as Partial<BackupFile>;
  if (file?.format !== 'open-problems-atlas-backup') {
    throw new ImportError('That file was not exported by Open Problems Atlas.');
  }
  if (file.version !== 1) {
    throw new ImportError(`Backup version ${String(file.version)} is not supported by this build.`);
  }
  if (!file.data || typeof file.data !== 'object') {
    throw new ImportError('The backup file has no data section.');
  }
  return file.data;
}

